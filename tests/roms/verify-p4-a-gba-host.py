"""Host-only genuine mGBA SRAM write/cold-load test for the licensed MIT gba-tests SRAM ROM.

Run in TWO separate Python processes, first then cold. Accepts only the
known upstream test ROM by SHA-256 to avoid accessing personal game content.
All test-generated bytes live in a new Git-ignored app/build scratch folder.
The GBA game itself writes SRAM; the host snapshots via the Libretro save API.
"""
import ctypes as ct
import hashlib
import sys
from pathlib import Path

if len(sys.argv) != 5:
    raise SystemExit('Usage: verify-p4-a-gba-host.py first|cold PINNED_MGBA_SO MIT_SRAM_GBA IGNORED_WORKDIR')
stage, core_path, rom_path, work_path = sys.argv[1:]
assert stage in ('first', 'cold')
work = Path(work_path).resolve()
assert 'build' in work.parts, 'Refusing to write fixture data outside an ignored build directory'
if stage == 'first':
    assert not work.exists(), 'Use a fresh directory to avoid overwriting fixture data'
    work.mkdir(parents=True)
else:
    assert work.is_dir() and (work / 'saved-sram.bin').is_file()
(work / 'system').mkdir(exist_ok=True)
rom_bytes = Path(rom_path).read_bytes()
rom = ct.create_string_buffer(rom_bytes)
rom_sha = hashlib.sha256(rom_bytes).hexdigest()
assert rom_sha == 'a37ad99c31e3f805eb05a00e498b65bd78e6f43a0a139cd695bea1f88229af2c', 'Not the licensed pinned GBA SRAM fixture'
print('ROM_SHA256', rom_sha, flush=True)
core = ct.CDLL(core_path)

class GameInfo(ct.Structure):
    _fields_ = [('path', ct.c_char_p), ('data', ct.c_void_p),
                ('size', ct.c_size_t), ('meta', ct.c_char_p)]

Environment = ct.CFUNCTYPE(ct.c_bool, ct.c_uint, ct.c_void_p)
Video = ct.CFUNCTYPE(None, ct.c_void_p, ct.c_uint, ct.c_uint, ct.c_size_t)
Audio = ct.CFUNCTYPE(None, ct.c_int16, ct.c_int16)
AudioBatch = ct.CFUNCTYPE(ct.c_size_t, ct.POINTER(ct.c_int16), ct.c_size_t)
Poll = ct.CFUNCTYPE(None)
Input = ct.CFUNCTYPE(ct.c_int16, ct.c_uint, ct.c_uint, ct.c_uint, ct.c_uint)
frames = 0

@Environment
def environment(command, pointer):
    if not pointer: return False
    if command == 10: return ct.cast(pointer, ct.POINTER(ct.c_int))[0] in (0, 1, 2)
    if command in (9, 30, 31):
        ct.cast(pointer, ct.POINTER(ct.c_char_p))[0] = str(work / 'system').encode()
        return True
    if command == 17:
        ct.cast(pointer, ct.POINTER(ct.c_bool))[0] = False
        return True
    if command == 52:
        ct.cast(pointer, ct.POINTER(ct.c_uint))[0] = 2
        return True
    return command in (11, 16, 67)

@Video
def video(pointer, width, height, pitch):
    global frames
    if pointer and width == 240 and height == 160:
        frames += 1

@Audio
def audio(left, right): pass

@AudioBatch
def audio_batch(pointer, count): return count

@Poll
def poll(): pass

@Input
def input_state(port, device, index, key): return 0

for name, callback in [
    ('retro_set_environment', environment),
    ('retro_set_video_refresh', video),
    ('retro_set_audio_sample', audio),
    ('retro_set_audio_sample_batch', audio_batch),
    ('retro_set_input_poll', poll),
    ('retro_set_input_state', input_state),
]:
    fn = getattr(core, name)
    fn.argtypes = [type(callback)]
    fn(callback)

core.retro_load_game.argtypes = [ct.POINTER(GameInfo)]
core.retro_load_game.restype = ct.c_bool
core.retro_get_memory_data.argtypes = [ct.c_uint]
core.retro_get_memory_data.restype = ct.c_void_p
core.retro_get_memory_size.argtypes = [ct.c_uint]
core.retro_get_memory_size.restype = ct.c_size_t
core.retro_init()
info = GameInfo(str(Path(rom_path).resolve()).encode(),
                ct.cast(rom, ct.c_void_p), len(rom_bytes), None)
assert core.retro_load_game(ct.byref(info)), 'mGBA ROM load failed'
try:
    memory = core.retro_get_memory_data(0)
    initial_size = core.retro_get_memory_size(0)
    assert memory and initial_size in (32768, 131072), initial_size
    print('SRAM_SIZE_INITIAL', initial_size, flush=True)
    if stage == 'first':
        for _ in range(200): core.retro_run()
        size = core.retro_get_memory_size(0)
        assert size in (32768, 131072), size
        data = ct.string_at(memory, size)
        assert any(x != 255 for x in data), 'GBA ROM did not write SRAM'
        assert frames >= 190, frames
        (work / 'saved-sram.bin').write_bytes(data)
        print('PASS FIRST', 'bytes', size, 'frames', frames,
              'payload_sha256', hashlib.sha256(data).hexdigest(), flush=True)
    else:
        data = (work / 'saved-sram.bin').read_bytes()
        # Pinned mGBA reports a 128 KiB AUTODETECT save buffer at load,
        # then identifies this actual licensed SRAM cartridge as 32 KiB.
        assert len(data) == initial_size or (len(data) == 32768 and initial_size == 131072), (len(data), initial_size)
        if len(data) != initial_size:
            ct.memset(memory, 0xff, initial_size)
        ct.memmove(memory, data, len(data))
        assert ct.string_at(memory, len(data)) == data
        print('PASS COLD MEMORY READBACK BEFORE FRAMES',
              hashlib.sha256(data).hexdigest(), flush=True)
        for _ in range(24): core.retro_run()
        assert frames >= 20, frames
        size_after = core.retro_get_memory_size(0)
        assert size_after == len(data), (size_after, len(data))
        assert ct.string_at(memory, len(data)) == data
        print('PASS COLD: independent mGBA process booted real fixture with restored SRAM', flush=True)
finally:
    core.retro_unload_game()
    core.retro_deinit()
